/* Fase 5: client is read-only, calculation rules and security gate. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=p=>readFileSync(p,'utf8');
const js=read('maker-rewards.js'),page=read('mijn-verdiensten.html');
new vm.Script(js,{filename:'maker-rewards.js'});
assert.match(page,/maker-rewards\.js\?v=1/);
assert.match(page,/id="reward-limit"/);
assert.match(page,/id="reward-progress"/);
assert.match(page,/id="reward-threshold"/);
assert.match(page,/€1,00/);
assert.match(page,/€1,50/);
assert.match(page,/€2,00/);
assert.match(page,/€3,00/);
assert.match(page,/€4,00/);
assert.match(js,/maker_reward_summary/);
assert.match(js,/maker_reward_units/);
assert.match(js,/maker_payouts/);
assert.match(js,/5000/);
assert.doesNotMatch(js,/\.(?:insert|update|upsert|delete)\s*\(/,'Client must never mutate rewards or payouts');
assert.doesNotMatch(page,/<button[^>]*>UITBETALING AANVRAGEN/,'Payout must remain disabled');
const base={shirt:100,sweater:150,hoodie:200};
const reward=(type,designCount)=>base[type]*(designCount>=26?2:1);
const cases=[['shirt',25,100],['shirt',26,200],['sweater',25,150],['sweater',26,300],['hoodie',25,200],['hoodie',26,400]];
for(const [type,count,expected] of cases)assert.equal(reward(type,count),expected);
assert.equal([reward('shirt',24),reward('sweater',25),reward('hoodie',26)].reduce((a,b)=>a+b,0),100+150+400);
const limit=sales=>sales>=25?6:3;
assert.equal(limit(24),3);assert.equal(limit(25),6);
console.log('DRAAGHET fase 5 preflight OK: read-only rewards UI, price tiers, 25/26, 3/6 and payout locked.');
